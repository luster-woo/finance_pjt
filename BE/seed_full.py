CommunityPost.objects.filter(title__in=existing_titles).delete()

created_p = 0
created_c = 0

for pd in POSTS_DATA:
    author = ru()
    stock_obj = find_stock(pd['stock']) if pd['stock'] else None

    post = CommunityPost.objects.create(
        user=author,
        stock=stock_obj,
        category='토론',
        title=pd['title'],
        content=pd['content'],
        likes_count=pd['likes'],
        view_count=random.randint(pd['likes'] * 3, pd['likes'] * 12),
    )
    created_p += 1

    # 좋아요
    like_users = random.sample(all_users, min(pd['likes'], len(all_users)))
    PostLike.objects.bulk_create(
        [PostLike(user=u, post=post) for u in like_users], ignore_conflicts=True
    )

    prev_comment = None
    for cdata in pd['comments']:
        nick, content, parent_flag = cdata[0], cdata[1], cdata[2] if len(cdata) > 2 else None
        comment_user = nick_map.get(nick, ru())
        parent = prev_comment if parent_flag else None

        c = Comment.objects.create(post=post, user=comment_user, parent=parent, content=content)

        n_likes = random.randint(1, 9)
        clikes = random.sample(all_users, min(n_likes, len(all_users)))
        CommentLike.objects.bulk_create(
            [CommentLike(user=u, comment=c) for u in clikes], ignore_conflicts=True
        )
        c.likes_count = n_likes
        c.save(update_fields=['likes_count'])
        created_c += 1
        prev_comment = c

print(f'[2] 게시글 {created_p}개 생성')
